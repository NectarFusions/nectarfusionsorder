import { createClient } from "@supabase/supabase-js";
import { Resend } from "resend";

const FROM = "NectarFusions NFOS <orders@nectar-fusions.com>";
const APP_URL = () => `${String(process.env.SITE_URL || "https://nectar-fusions.com").replace(/\/$/,"")}/admin/operations`;

const esc = (value) =>
  String(value ?? "").replace(/[<>&"]/g, (ch) => ({
    "<":"&lt;", ">":"&gt;", "&":"&amp;", '"':"&quot;",
  })[ch]);

const emailHtml = ({ member, notification }) => `
  <div style="font-family:Arial,sans-serif;max-width:620px;margin:auto;color:#17383d">
    <h2 style="margin-bottom:8px">NectarFusions Operations</h2>
    <p>Hi ${esc(member.display_name || "there")},</p>
    <p><strong>${esc(notification.title)}</strong></p>
    ${notification.detail ? `<p>${esc(notification.detail)}</p>` : ""}
    <p>
      <strong>Severity:</strong> ${esc(notification.severity)}<br>
      ${notification.due_date ? `<strong>Due:</strong> ${esc(notification.due_date)}<br>` : ""}
      ${notification.route ? `<strong>Area:</strong> ${esc(notification.route)}` : ""}
    </p>
    <p><a href="${APP_URL()}" style="display:inline-block;padding:10px 16px;border-radius:7px;background:#17383d;color:white;text-decoration:none">Open NFOS</a></p>
    <p style="font-size:12px;color:#667">This alert was generated by the NFOS operations system.</p>
  </div>`;

export default async () => {
  const url = String(process.env.SUPABASE_URL || "").trim();
  const serviceKey = String(process.env.SUPABASE_SERVICE_ROLE_KEY || "").trim();
  const resendKey = String(process.env.RESEND_API_KEY || "").trim();

  if (!url || !serviceKey || !resendKey) {
    return Response.json({ ok:false, error:"NFOS email delivery is missing required environment variables." }, { status:500 });
  }

  const db = createClient(url, serviceKey, {
    auth:{ persistSession:false, autoRefreshToken:false, detectSessionInUrl:false },
  });
  const resend = new Resend(resendKey);

  const { error: syncError } = await db.rpc("nfos_sync_notifications");
  if (syncError) {
    return Response.json({ ok:false, error:syncError.message }, { status:500 });
  }

  const { data: deliveries, error: deliveryError } = await db
    .from("nfos_notification_deliveries")
    .select("id,notification_id,attempt_count")
    .eq("channel","email")
    .eq("status","pending")
    .lt("attempt_count",5)
    .order("created_at",{ascending:true})
    .limit(50);

  if (deliveryError) {
    return Response.json({ ok:false, error:deliveryError.message }, { status:500 });
  }

  let sent=0, failed=0, cancelled=0;

  for (const delivery of deliveries || []) {
    const { data: notification } = await db
      .from("nfos_notifications")
      .select("id,recipient_member_id,title,detail,severity,route,due_date,status")
      .eq("id",delivery.notification_id)
      .maybeSingle();

    if (!notification || notification.status==="resolved") {
      await db.from("nfos_notification_deliveries").update({
        status:"cancelled",updated_at:new Date().toISOString(),
      }).eq("id",delivery.id);
      cancelled += 1;
      continue;
    }

    const { data: member } = await db
      .from("nfos_team_members")
      .select("display_name,email,active")
      .eq("id",notification.recipient_member_id)
      .maybeSingle();

    if (!member?.active || !member?.email) {
      await db.from("nfos_notification_deliveries").update({
        status:"failed",
        attempt_count:Number(delivery.attempt_count || 0)+1,
        last_attempt_at:new Date().toISOString(),
        error_message:"Active team member email is unavailable.",
        updated_at:new Date().toISOString(),
      }).eq("id",delivery.id);
      failed += 1;
      continue;
    }

    try {
      const result = await resend.emails.send({
        from:FROM,
        to:member.email,
        subject:`${notification.severity==="critical" ? "URGENT — " : ""}${notification.title}`,
        html:emailHtml({ member, notification }),
      });

      if (result?.error) throw new Error(result.error.message || "Resend rejected the email.");

      await db.from("nfos_notification_deliveries").update({
        status:"sent",
        attempt_count:Number(delivery.attempt_count || 0)+1,
        last_attempt_at:new Date().toISOString(),
        sent_at:new Date().toISOString(),
        provider:"resend",
        provider_message_id:result?.data?.id || null,
        error_message:null,
        updated_at:new Date().toISOString(),
      }).eq("id",delivery.id);
      sent += 1;
    } catch (error) {
      await db.from("nfos_notification_deliveries").update({
        status:"failed",
        attempt_count:Number(delivery.attempt_count || 0)+1,
        last_attempt_at:new Date().toISOString(),
        provider:"resend",
        error_message:String(error?.message || error).slice(0,1000),
        updated_at:new Date().toISOString(),
      }).eq("id",delivery.id);
      failed += 1;
    }
  }

  return Response.json({ ok:true, processed:(deliveries || []).length, sent, failed, cancelled });
};

export const config = {
  schedule:"@hourly",
};
